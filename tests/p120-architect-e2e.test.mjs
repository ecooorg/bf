import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { spawn, spawnSync } from 'node:child_process';
import net from 'node:net';
import JSZip from 'jszip';
import { chromium } from 'playwright';
import { runStaticValidators } from '../appBuilder/validator-static-site.ts';

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const freePort = () => new Promise((resolve, reject) => {
  const server = net.createServer();
  server.once('error', reject);
  server.listen(0, '127.0.0.1', () => {
    const address = server.address();
    server.close((error) => error ? reject(error) : resolve(address.port));
  });
});

const json = (data, status = 200) => ({
  status,
  contentType: 'application/json',
  body: JSON.stringify({ success: true, data }),
});

test('P120.0.3 Architect browser scenario: create, validate evidence, download and inspect source ZIP', async (t) => {
  if (!existsSync('dist/index.html')) {
    const build = spawnSync('npm', ['run', 'build'], { stdio: 'inherit', timeout: 180_000 });
    assert.equal(build.status, 0, 'npm run build must succeed before the Architect browser scenario');
  }

  const fixtureZip = new JSZip();
  fixtureZip.file('index.html', '<!doctype html><html><head><title>Fixture app</title></head><body><main id="app">Ready</main></body></html>');
  fixtureZip.file('README.md', '# Fixture app\n\nGenerated by the deterministic P120.0.3 browser fixture.\n');
  fixtureZip.file('package.json', JSON.stringify({ name: 'fixture-app', private: true, scripts: { start: 'node server.js' } }, null, 2));
  fixtureZip.file('server.js', "const http = require('http');\nhttp.createServer((_req, res) => res.end('ok')).listen(3000);\n");
  const zipBytes = await fixtureZip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });

  const port = await freePort();
  const base = `http://127.0.0.1:${port}`;
  const server = spawn('tsx', ['server.ts'], {
    stdio: ['ignore', 'pipe', 'pipe'],
    env: {
      ...process.env,
      NODE_ENV: 'production',
      PORT: String(port),
      APP_PASSWORD: 'p120-architect-test-password',
      SESSION_SECRET: 'p120-architect-session-secret-'.padEnd(40, 'x'),
      GEMINI_API_KEY: 'not-used-browser-mock-key',
      DATABASE_URL: '',
      ENABLE_PROJECT_MODE: 'false',
    },
  });
  let serverOutput = '';
  server.stdout.on('data', (chunk) => { serverOutput += chunk; });
  server.stderr.on('data', (chunk) => { serverOutput += chunk; });
  let browser;

  try {
    let healthy = false;
    for (let attempt = 0; attempt < 120; attempt++) {
      if (server.exitCode !== null) throw new Error(`server exited before ready:\n${serverOutput}`);
      try {
        const response = await fetch(`${base}/api/health`);
        if (response.ok) { healthy = true; break; }
      } catch {}
      await sleep(250);
    }
    assert.equal(healthy, true, `server did not become healthy:\n${serverOutput}`);

    browser = await chromium.launch();
    const context = await browser.newContext({ acceptDownloads: true, viewport: { width: 1280, height: 900 } });
    const page = await context.newPage();
    page.setDefaultTimeout(10_000);

    const projectId = 'p120-architect-fixture-project';
    const projectName = 'P120 verified fixture app';
    const apiCalls = [];
    let projectState = {};
    let buildPayload = null;
    let downloadRequests = 0;
    const checksRun = ['html-structure', 'js-syntax', 'refs', 'size', 'secrets', 'acceptance', 'dom-wiring'];
    const project = () => ({
      id: projectId,
      name: projectName,
      status: 'active',
      state: projectState,
      state_version: projectState.passport?.status === 'confirmed' ? 2 : 1,
    });

    await page.route('**/api/session', (route) => route.fulfill({
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify({ authenticated: true, projectModeEnabled: true, capabilities: { programZip: true } }),
    }));
    await page.route('**/api/projects**', async (route) => {
      const request = route.request();
      const url = new URL(request.url());
      const path = url.pathname;
      apiCalls.push({ method: request.method(), path, body: request.postDataJSON() });

      if (path === '/api/projects' && request.method() === 'GET') {
        return route.fulfill(json(projectState.passport ? [project()] : []));
      }
      if (path === '/api/projects' && request.method() === 'POST') {
        const body = request.postDataJSON();
        assert.equal(typeof body.name, 'string');
        assert.ok(body.goal.length >= 8, "project creation must include the user's goal");
        projectState = {};
        return route.fulfill(json(project()));
      }
      if (path === `/api/projects/${projectId}/state` && request.method() === 'PUT') {
        const body = request.postDataJSON();
        assert.equal(body.expected_version, 1);
        assert.equal(body.state.passport.status, 'confirmed', 'the user-confirmed project passport must be saved before build');
        projectState = body.state;
        return route.fulfill(json({ state_version: 2 }));
      }
      if (path === `/api/projects/${projectId}/code/build` && request.method() === 'POST') {
        buildPayload = request.postDataJSON();
        assert.ok(buildPayload.goal.includes('community notice board'));
        return route.fulfill(json({
          status: 'done',
          outcome: 'SUCCESS',
          goalImplemented: true,
          downloadUrl: '/test-artifacts/p120-source.zip',
          note: 'Deterministic browser fixture; all declared validators passed.',
          report: { outcome: 'SUCCESS', checksDeclared: checksRun, checksRun, checksNotRun: [], failureReason: null },
          codeTask: { status: 'done', statusReason: 'All declared validators passed.' },
        }));
      }
      if (path === `/api/projects/${projectId}` && request.method() === 'GET') {
        return route.fulfill(json(project()));
      }
      if (path.startsWith(`/api/projects/${projectId}/`)) {
        return route.fulfill(json([]));
      }
      return route.fulfill({ status: 404, contentType: 'application/json', body: JSON.stringify({ success: false, error: `Unexpected mocked API path: ${path}` }) });
    });
    await page.route('**/test-artifacts/p120-source.zip', async (route) => {
      downloadRequests++;
      await route.fulfill({
        status: 200,
        contentType: 'application/zip',
        headers: { 'content-disposition': 'attachment; filename="p120-source.zip"' },
        body: zipBytes,
      });
    });

    await page.goto(`${base}/project`);
    await page.getByTestId('path-novice').waitFor();
    await page.getByTestId('path-novice').click();
    const idea = 'Build a community notice board where people can post short updates.';
    await page.getByLabel('What do you want to build? (ordinary language)').fill(idea);
    await page.getByRole('button', { name: 'Next' }).click();
    await page.getByRole('button', { name: /Website \/ web app/ }).click();
    await page.getByRole('button', { name: 'Next' }).click();
    await page.getByRole('button', { name: 'No', exact: true }).first().click();
    await page.getByRole('button', { name: 'No', exact: true }).nth(1).click();
    await page.getByRole('button', { name: 'English', exact: true }).click();
    await page.getByRole('button', { name: 'Next' }).click();
    await page.getByRole('button', { name: 'Choose for me' }).click();
    await page.getByRole('button', { name: 'Create project & build ZIP' }).click();

    await page.getByTestId('novice-done').waitFor();
    await page.getByRole('link', { name: 'Download source ZIP' }).waitFor();
    await page.getByText(/Source ZIP ready/).waitFor();
    assert.deepEqual(buildPayload && [buildPayload.kind, buildPayload.needsAuth, buildPayload.needsDb, buildPayload.language, buildPayload.stack], ['website', 'no', 'no', 'en', 'auto']);
    assert.ok(checksRun.every((name) => name.length > 0));
    assert.equal(apiCalls.filter((call) => call.path === `/api/projects/${projectId}/code/build`).length, 1, 'the wizard must start exactly one build');

    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('link', { name: 'Download source ZIP' }).click();
    const download = await downloadPromise;
    assert.equal(download.suggestedFilename(), 'p120-source.zip');
    const downloadedPath = await download.path();
    assert.ok(downloadedPath, 'browser must produce a local download');
    const downloadedBytes = await readFile(downloadedPath);
    assert.ok(downloadedBytes.byteLength > 0, 'downloaded ZIP must not be empty');
    assert.equal(downloadRequests, 1, 'the download link must request the artifact once');

    const inspectedZip = await JSZip.loadAsync(downloadedBytes);
    const files = Object.values(inspectedZip.files).filter((entry) => !entry.dir);
    const names = files.map((entry) => entry.name).sort();
    assert.deepEqual(names, ['README.md', 'index.html', 'package.json', 'server.js']);
    assert.ok(files.every((entry) => !entry.name.startsWith('/') && !entry.name.split('/').includes('..')), 'ZIP must not contain absolute or traversal paths');
    const sourceFiles = new Map();
    for (const entry of files) sourceFiles.set(entry.name, await inspectedZip.file(entry.name).async('string'));
    assert.match(sourceFiles.get('index.html'), /id="app"/);
    assert.ok(sourceFiles.get('package.json').length > 0);
    const validation = runStaticValidators(sourceFiles, { acceptance: ['has_file:index.html', 'has_file:README.md', 'html_has:index.html:#app'] });
    assert.deepEqual(validation.map((check) => check.name), checksRun, 'the real static validator set must run in its declared order');
    assert.deepEqual(validation.filter((check) => !check.ok).map((check) => ({ name: check.name, issues: check.issues })), [], 'downloaded ZIP contents must pass all seven static validators');

    await context.close();
    t.diagnostic('Coverage: real local app server and Architect browser UI; mocked deterministic project/build API; user-confirmed passport; actual browser download; non-empty ZIP, expected source files and safe archive paths; all seven real static validators run locally against downloaded contents. Live builder/provider execution is not covered by this fixture.');
  } finally {
    if (browser) await browser.close().catch(() => {});
    if (server.exitCode === null) {
      server.kill('SIGTERM');
      await Promise.race([
        new Promise((resolve) => server.once('exit', resolve)),
        sleep(3000),
      ]);
      if (server.exitCode === null) server.kill('SIGKILL');
    }
  }
});
